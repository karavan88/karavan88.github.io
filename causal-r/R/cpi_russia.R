# cpi_russia.R — индекс потребительских цен, Россия, декабрь к декабрю (%), Росстат.
# Используется для перевода номинальных рублей в цены базового года.
# Источник: Росстат (сводка statbureau.org, проверено 2026-10-03); 2025 — 5,6 %.
# Опрос RLMS проходит в октябре–декабре, поэтому декабрьский индекс — разумное приближение.

cpi_russia <- tibble::tribble(
  ~year, ~infl_dec,
  2000, 20.20, 2001, 18.58, 2002, 15.06, 2003, 11.99, 2004, 11.74,
  2005, 10.91, 2006,  9.00, 2007, 11.87, 2008, 13.28, 2009,  8.80,
  2010,  8.78, 2011,  6.10, 2012,  6.58, 2013,  6.45, 2014, 11.36,
  2015, 12.91, 2016,  5.38, 2017,  2.52, 2018,  4.27, 2019,  3.05,
  2020,  4.91, 2021,  8.39, 2022, 11.92, 2023,  7.42, 2024,  9.51,
  2025,  5.60
)

# Накопленный индекс: уровень цен в декабре каждого года, базовый год = 2024 (= 100).
cpi_russia$price_level <- cumprod(1 + cpi_russia$infl_dec / 100)
cpi_russia$cpi_2024 <- 100 * cpi_russia$price_level /
  cpi_russia$price_level[cpi_russia$year == 2024]
cpi_russia$price_level <- NULL

# Перевод номинальной суммы года `year` в рубли 2024 года:
to_rub_2024 <- function(x, year) {
  idx <- cpi_russia$cpi_2024[match(year, cpi_russia$year)]
  x / idx * 100
}
